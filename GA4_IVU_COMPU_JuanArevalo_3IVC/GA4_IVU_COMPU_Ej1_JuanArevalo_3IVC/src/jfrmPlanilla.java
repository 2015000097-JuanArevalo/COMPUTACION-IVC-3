    private void jbtnInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnInsertarActionPerformed
        // TODO add your handling code here:
        totalSalario();
        modelo.addRow(new Object[]
        {
            jtxtDPI.getText(),
            jtxtNombre.getText(),
            jtxtApellido.getText(),
            jtxtSalario.getText(),
            jcbxCategoria.getSelectedItem(),
            jcbxPuesto.getSelectedItem(),
            total
        }        
        );
        limpiarCajas();
    }//GEN-LAST:event_jbtnInsertarActionPerformed

    private void jtabDatosMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtabDatosMousePressed
        // TODO add your handling code here:
        int fila = jtabDatos.getSelectedRow();
        jtxtDPI.setText(jtabDatos.getValueAt(fila, 0).toString());
        jtxtNombre.setText(jtabDatos.getValueAt(fila, 1).toString());
        jtxtApellido.setText(jtabDatos.getValueAt(fila, 2).toString());
        jtxtSalario.setText(jtabDatos.getValueAt(fila, 3).toString());
        jcbxCategoria.setSelectedItem(jtabDatos.getValueAt(fila, 4));
        jcbxPuesto.setSelectedItem(jtabDatos.getValueAt(fila, 5));
    }//GEN-LAST:event_jtabDatosMousePressed

    private void jbtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnEliminarActionPerformed
        // TODO add your handling code here:
        if(modelo.getRowCount() <= 0)
            JOptionPane.showMessageDialog(null, "¡No hay registros!", "Alerta", JOptionPane.WARNING_MESSAGE);
        else
        {
            modelo.removeRow(jtabDatos.getSelectedRow());
            JOptionPane.showMessageDialog(null, "¡Registro elimindo!", "Completado", JOptionPane.INFORMATION_MESSAGE);
            limpiarCajas();
        }
    }//GEN-LAST:event_jbtnEliminarActionPerformed

    private void jbtnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnEditarActionPerformed
        // TODO add your handling code here:
        int fila = jtabDatos.getSelectedRow();
        modelo.setValueAt(jtxtDPI.getText(), fila, 0);
        modelo.setValueAt(jtxtNombre.getText(), fila, 1);
        modelo.setValueAt(jtxtApellido.getText(), fila, 2);
        modelo.setValueAt(jtxtSalario.getText(), fila, 3);
        modelo.setValueAt(jcbxCategoria.getSelectedItem(), fila, 4);
        modelo.setValueAt(jcbxPuesto.getSelectedItem(), fila, 5);
        totalSalario();
        modelo.setValueAt(total, fila, 6);
        limpiarCajas();
    }//GEN-LAST:event_jbtnEditarActionPerformed

    private void jbtnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnImprimirActionPerformed
        // TODO add your handling code here:
        MessageFormat Header = new MessageFormat("Planilla 2026");
        MessageFormat Footer = new MessageFormat("Página {0}");
        try{
            PrintRequestAttributeSet set = new HashPrintRequestAttributeSet();
            set.add(OrientationRequested.LANDSCAPE);
            jtabDatos.print(JTable.PrintMode.FIT_WIDTH, Header, Footer, true, set, true);
            JOptionPane.showMessageDialog(null, "\n ¡Impreso con éxito!", "Completado", JOptionPane.INFORMATION_MESSAGE);
        }
        catch (java.awt.print.PrinterException e){
            JOptionPane.showMessageDialog(null, "\n¡Fallido!\n" + e, "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jbtnImprimirActionPerformed

